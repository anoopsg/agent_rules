#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

SRC_DIR="$PROJECT_ROOT/src"
ALL_TARGETS=(antigravity claude cursor kiro)

VERSION="dev"
REPO_NAME="anoopsg/agent_rules"
OUTPUT_DIR=""
TARGETS=()
GEN_EXCLUSIVE=false
GEN_CLEAN=false

# Color only on a TTY, and never with NO_COLOR.
if [[ -t 1 && -z "${NO_COLOR:-}" ]]; then
  C_CYAN=$'\033[36m'; C_RESET=$'\033[0m'
else
  C_CYAN=""; C_RESET=""
fi

version_label() {
  if [[ "$VERSION" == "dev" ]]; then echo "dev"; else echo "v$VERSION"; fi
}

show_banner() {
  printf '%s' "$C_CYAN"
  cat <<'BANNER'
    _                    _
   / \   __ _  ___ _ __ | |___  __
  / _ \ / _` |/ _ \ '_ \| __\ \/ /
 / ___ \ (_| |  __/ | | | |_ >  <
/_/   \_\__, |\___|_| |_|\__/_/\_\
        |___/
BANNER
  printf '%s' "$C_RESET"
  printf '  Vendor-agnostic agent rules & skills generator (%s)\n\n' \
    "$(version_label)"
}

resolve_target() {
  case "$1" in
    ag|antigravity) echo "antigravity" ;;
    cl|claude)      echo "claude" ;;
    cu|cursor)      echo "cursor" ;;
    kr|kiro)        echo "kiro" ;;
    *) return 1 ;;
  esac
}

show_help() {
  show_banner
  cat <<'EOF'
USAGE
  agentx [options] <output-dir>

ARGUMENTS
  <output-dir>          Project directory to generate into. The tool
                        creates .cursor/ and/or .agents/ inside it.

OPTIONS
  -t, --targets <list>  Comma-separated agents (default: all).
                        Values: antigravity (ag), claude (cl), cursor (cu), kiro (kr)
  -e, --exclusive       Include opt-in content from exclusive/.
  -c, --clean           Remove files generated by the previous run
                        before writing (keeps hand-added files).
  -u, --update          Update the agentx binary to the latest release.
  -v, --version         Show version and exit.
  -h, --help            Show this help message and exit.

EXAMPLES
  # All agents in the current directory
  agentx .
  # All agents + exclusive (Launchpad) content
  agentx -e .
  # Clean stale output, then regenerate
  agentx -c .
  # Only Antigravity
  agentx -t ag .
  # Only Claude Code CLI
  agentx -t cl .
  # Cursor + Antigravity + Kiro with exclusive content
  agentx -t ag,cu,kr -e .
EOF
}

# Subshell keeps each vendor's functions from leaking into the next.
run_target() {
  local sources=("$SRC_DIR")
  [[ "$GEN_EXCLUSIVE" == true ]] && sources+=("$SRC_DIR/exclusive")
  (
    source "$SCRIPT_DIR/_agents/_lib.sh"
    # shellcheck disable=SC1090
    source "$SCRIPT_DIR/_agents/$1.sh"
    generate "$OUTPUT_DIR" "$GEN_CLEAN" "${sources[@]}"
    printf '  %-12s -> %s\n' "$1" "$OUTPUT_DIR/$VENDOR_DIR"
  )
}

# Replaces the bundled binary with the latest release. AGENTX_SELF_PATH is
# set by the release stub, so this only works for the bundle.
do_update() {
  if [[ -z "${AGENTX_SELF_PATH:-}" ]]; then
    echo "Error: --update is only supported for the compiled agentx binary."
    echo "If you are developing from source, update via git instead."
    exit 1
  fi

  if [[ ! -f "$AGENTX_SELF_PATH" ]]; then
    echo "Error: Could not resolve the path to the agentx binary."
    exit 1
  fi

  local target_bin
  target_bin="$(cd "$(dirname "$AGENTX_SELF_PATH")" && pwd)/$(basename "$AGENTX_SELF_PATH")"

  local release_url="https://github.com/${REPO_NAME}/releases/latest/download/agentx"
  echo "Checking for updates from ${release_url}..."

  local tmp_bin
  tmp_bin="$(mktemp)"
  trap 'rm -f "$tmp_bin"' EXIT

  if command -v curl >/dev/null 2>&1; then
    curl --fail --silent --show-error --location "$release_url" -o "$tmp_bin"
  elif command -v wget >/dev/null 2>&1; then
    wget --quiet -O "$tmp_bin" "$release_url"
  else
    echo "Error: curl or wget is required to download updates."
    exit 1
  fi

  if ! grep -q "__PAYLOAD__" "$tmp_bin"; then
    echo "Error: Downloaded file appears invalid (missing payload marker)."
    echo "Update aborted."
    exit 1
  fi

  local new_version
  new_version=$(
    sed -n 's/^# agentx-version: *//p' "$tmp_bin"
  ) || true

  if [[ -n "$new_version" \
    && "$new_version" == "$VERSION" ]]; then
    echo "agentx is already up-to-date (v$VERSION)."
    exit 0
  fi

  echo "Updating $target_bin..."
  chmod +x "$tmp_bin"
  if cp "$tmp_bin" "$target_bin"; then
    echo "Successfully updated agentx!"
    "$target_bin" --version
  else
    echo "Error: Failed to write to $target_bin."
    echo "Try re-running with elevated permissions (e.g., sudo)."
    exit 1
  fi
  exit 0
}

main() {
  while [[ $# -gt 0 ]]; do
    case "$1" in
      -t|--targets)
        shift
        if [[ $# -eq 0 || "$1" == -* ]]; then
          echo "Error: --targets requires a value." >&2
          exit 1
        fi
        IFS=',' read -ra _targets <<< "$1"
        for _t in "${_targets[@]}"; do
          _resolved="$(resolve_target "$_t")" || {
            echo "Error: unknown target '$_t'." >&2
            echo "Valid: antigravity (ag), claude (cl), cursor (cu), kiro (kr)" >&2
            exit 1
          }
          TARGETS+=("$_resolved")
        done
        shift
        ;;
      -e|--exclusive)
        GEN_EXCLUSIVE=true
        shift
        ;;
      -c|--clean)
        GEN_CLEAN=true
        shift
        ;;
      -u|--update)
        if [[ $# -gt 1 ]]; then
          echo "Error: --update cannot be combined with other arguments." >&2
          exit 1
        fi
        do_update
        ;;
      -v|--version)
        echo "agentx $(version_label)"
        exit 0
        ;;
      -h|--help)
        show_help
        exit 0
        ;;
      -*)
        echo "Error: unknown option: $1" >&2
        echo "Run 'agentx --help' for usage." >&2
        exit 1
        ;;
      *)
        if [[ -z "$OUTPUT_DIR" ]]; then
          OUTPUT_DIR="$1"
          shift
        else
          echo "Error: multiple output directories" \
            "specified: $OUTPUT_DIR and $1" >&2
          exit 1
        fi
        ;;
    esac
  done

  if [[ -z "$OUTPUT_DIR" ]]; then
    show_help
    echo "Error: an output directory is required." >&2
    exit 1
  fi

  local resolved_output
  resolved_output="$(
    cd "${OUTPUT_DIR}" 2>/dev/null && pwd || echo ""
  )"
  if [[ -n "$resolved_output" \
    && "$resolved_output" == "$PROJECT_ROOT" ]]; then
    echo "Warning: generating into the repository root." >&2
    echo "For local testing, prefer: bin/agentx.sh -e gen" >&2
    echo ""
  fi

  local mode="generate"
  [[ "$GEN_CLEAN" = true ]] && mode="clean + generate"
  echo "agentx $mode ($(version_label))"

  [[ ${#TARGETS[@]} -eq 0 ]] && TARGETS=("${ALL_TARGETS[@]}")
  local target
  for target in $(printf '%s\n' "${TARGETS[@]}" | sort -u); do
    run_target "$target"
  done

  echo "Done."
}

main "$@"
